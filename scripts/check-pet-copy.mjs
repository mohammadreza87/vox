#!/usr/bin/env node
/**
 * Pet copy lint (care game design §5.6, PET_COPY_KEYS "Lint", PET_PERSIAN_COPY §D, PET_PERSIAN_VOICE §4.4-4.7, §7.1):
 * every pet string in both languages, failing on guilt, missing-you, suffering needs, FOMO, pressure, Persian
 * absence reproach, counting absence and streaks; digits in the pet voice (any) and in Persian system strings
 * (Latin or Arabic-Indic; Persian ۰-۹ only); Arabic ي ك ى ة in Persian; Latin ? , ; in Persian; emoji in pet
 * bubbles (🍉 ✨ 🌱 allowed on check-in DM keys only).
 *
 *   node scripts/check-pet-copy.mjs [--json]
 *
 * Sources: `src/app/studio/pet/_ui/strings/{en,fa}.ts` once they exist (voice from a key→voice map in that folder,
 * such as voice.ts `NOT_SYSTEM` with its `?? 'system'` fallback; with no map, keys prefixed sys./perm./err./quiet.
 * are system and the rest pet), plus the server's generated check-in copy `src/lib/pet/checkin-copy.ts` (voice from its own
 * CHECKIN_VOICE map) and any template or copy file in `src/lib/studio/pet-checkins/` (`*templates*.ts`, `*copy*.ts`: pet
 * voice, DM keys; the planner and delivery code beside them are not copy). Until the strings module lands it scans today's copy:
 * `copy.ts`, `circle-copy.ts` and SOUVENIRS in `pet-http.ts`, with a fixed voice table for those. It prints which
 * sources it used. One line per violation, `file:key: rule: excerpt`; exit 1 on any. Sibling of check-pet-bundle.mjs;
 * both run under `npm run check:pet`.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DM_PREFIX, VOICES, excerpt, extractStrings, fallbackVoiceFrom, isCopy, joinPath, lintText, voiceFor, voiceMapFrom } from './lib/pet-copy-lint.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const UI = 'src/app/studio/pet/_ui';
const STRINGS_DIR = `${UI}/strings`;
const CHECKINS_DIR = 'src/lib/studio/pet-checkins';
/** Only these files in CHECKINS_DIR hold copy; the planner, store and delivery modules there are code. */
const CHECKIN_TEMPLATE_FILE = /(templates|copy)[\w.-]*\.ts$/;
/** The server's check-in copy, generated by strings/generate.mjs (renderCheckinCopy) with its own voice map. */
const CHECKIN_COPY = 'src/lib/pet/checkin-copy.ts';
const tsFiles = (dir) => existsSync(dir)
  ? readdirSync(dir).filter((f) => /\.tsx?$/.test(f) && !/\.(test|spec)\.tsx?$/.test(f) && !f.endsWith('.d.ts')).sort()
  : [];

/**
 * Today's copy and its voice, until the strings module replaces it (PET_PERSIAN_COPY §A: circle-copy is system voice;
 * SAY and SOUVENIRS are the pet; in copy.ts COPY the quiet screens and buttons are system, the rest the pet's).
 */
const LEGACY = [
  { file: `${UI}/copy.ts`, decls: ['SAY', 'sayText', 'NEED_LABEL', 'COPY'],
    voice: (key) => /^NEED_LABEL\./.test(key) || /^COPY\.(\w+(Title|Body)|retry|close|more|less|send|feed|play|rest|holdToTalk|chatInTelegram|talkTo|score|daysTogether)$/.test(key) ? 'system' : 'pet' },
  { file: `${UI}/circle-copy.ts`, decls: ['COPY'], voice: () => 'system' },
  { file: 'src/lib/studio/pet-http.ts', decls: ['SOUVENIRS'], voice: () => 'pet' },
];

/** @returns {{ sources: { file: string, mode: string }[], entries: { file: string, key: string, text: string, voice: string, dm: boolean, line: number }[], notes: string[] }} */
export function collect(root = ROOT) {
  const sources = [], entries = [], notes = [];
  const read = (rel) => readFileSync(join(root, rel), 'utf8');
  const stringsFiles = ['en.ts', 'fa.ts'].filter((f) => existsSync(join(root, STRINGS_DIR, f)));
  if (stringsFiles.length) {
    const voiceMap = new Map(), voiceDecls = new Set();
    let fallback = null;
    for (const f of tsFiles(join(root, STRINGS_DIR))) {
      const src = read(`${STRINGS_DIR}/${f}`);
      const found = voiceMapFrom(extractStrings(src));
      if (!found.map.size) continue;
      for (const [k, v] of found.map) voiceMap.set(k, v);
      for (const d of found.decls) voiceDecls.add(d);
      fallback ??= fallbackVoiceFrom(src);
    }
    notes.push(voiceMap.size
      ? `voice from the strings module's key→voice map (${[...voiceDecls].join(', ')}: ${voiceMap.size} keys; unmapped keys are ${fallback ?? ([...voiceMap.values()].includes('system') ? 'by prefix' : 'system')})`
      : 'no key→voice map exported: keys prefixed sys./perm./err./quiet. are system voice, the rest pet voice');
    for (const f of stringsFiles) {
      const file = `${STRINGS_DIR}/${f}`;
      sources.push({ file, mode: 'strings module' });
      for (const e of extractStrings(read(file))) {
        if (voiceDecls.has(e.decl) || !isCopy(e.text)) continue;
        const key = joinPath(e.path.length > 1 ? e.path.slice(1) : e.path);
        entries.push({ file, key, text: e.text, voice: voiceFor(key, voiceMap, fallback).voice, dm: DM_PREFIX.test(key), line: e.line });
      }
    }
  } else {
    notes.push(`${STRINGS_DIR}/{en,fa}.ts not found: linting today's copy with a fixed voice table (copy.ts quiet screens and buttons, NEED_LABEL and circle-copy.ts are system; SAY, SOUVENIRS and the rest of copy.ts are pet)`);
    for (const { file, decls, voice } of LEGACY) {
      if (!existsSync(join(root, file))) { notes.push(`missing ${file}`); continue; }
      sources.push({ file, mode: `legacy: ${decls.join(', ')}` });
      for (const e of extractStrings(read(file))) {
        if (!decls.includes(e.decl) || !isCopy(e.text)) continue;
        entries.push({ file, key: e.key, text: e.text, voice: voice(e.key), dm: false, line: e.line });
      }
    }
  }
  if (existsSync(join(root, CHECKIN_COPY))) {
    const all = extractStrings(read(CHECKIN_COPY));
    const found = voiceMapFrom(all);
    sources.push({ file: CHECKIN_COPY, mode: `server check-in copy (voice from ${[...found.decls].join(', ') || 'key prefix'})` });
    for (const e of all) {
      if (found.decls.has(e.decl) || !isCopy(e.text)) continue;
      const key = joinPath(e.path.length > 1 ? e.path.slice(1) : e.path);
      entries.push({ file: CHECKIN_COPY, key, text: e.text, voice: voiceFor(key, found.map, 'system').voice, dm: DM_PREFIX.test(key), line: e.line });
    }
  }
  for (const f of tsFiles(join(root, CHECKINS_DIR)).filter((name) => CHECKIN_TEMPLATE_FILE.test(name))) {
    const file = `${CHECKINS_DIR}/${f}`;
    sources.push({ file, mode: 'check-in templates (pet voice, DM)' });
    for (const e of extractStrings(read(file))) {
      if (!isCopy(e.text) || VOICES.has(e.text)) continue;
      entries.push({ file, key: e.key, text: e.text, voice: 'pet', dm: true, line: e.line });
    }
  }
  return { sources, entries, notes };
}

export function run(root = ROOT) {
  const { sources, entries, notes } = collect(root);
  const violations = entries.flatMap((e) => lintText(e).map((v) => ({ file: e.file, line: e.line, key: e.key, voice: e.voice, rule: v.rule, match: v.match, excerpt: excerpt(e.text) })));
  return { sources, notes, strings: entries.length, violations };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = run();
  if (process.argv.includes('--json')) console.log(JSON.stringify(result, null, 2));
  else {
    for (const s of result.sources) console.log(`source ${s.file} (${s.mode})`);
    for (const n of result.notes) console.log(`note: ${n}`);
    for (const v of result.violations) console.log(`${v.file}:${v.key}: ${v.rule}: ${v.excerpt}`);
    console.log(`${result.strings} strings, ${result.violations.length} violation${result.violations.length === 1 ? '' : 's'}`);
  }
  if (result.violations.length) process.exit(1);
}
