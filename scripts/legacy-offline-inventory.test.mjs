test('post-guard invalid native JSON remains a minimized fixed-code report under poisoned loader variables', () => fixture(({ sourcePath, selectionPath, invoke, dir }) => {
  const malformed = Buffer.from('{"' + CANARY);
  writeFileSync(sourcePath, malformed); const selected = JSON.parse(readFileSync(selectionPath, 'utf8'));
  selected.expectedBytes = malformed.length; selected.expectedSha256 = createHash('sha256').update(malformed).digest('hex');
  writeFileSync(selectionPath, JSON.stringify(selected));
  const result = invoke(args, { env: { PATH: process.env.PATH, TSX_DEBUG: '1', ESBUILD_BINARY_PATH: join(dir, CANARY) } });
  assert.equal(result.status, 2); assert.equal(JSON.parse(result.stdout).stop, 'invalid_native_json');
  assert.equal(result.stderr, ''); assert.ok(!result.stdout.includes(CANARY));
  return malformed; // The outer assertion checks the deliberately malformed input stayed unchanged.
}));
