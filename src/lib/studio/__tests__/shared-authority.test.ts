import { afterEach, expect, it } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { sharedAuthorityFromStudioStore } from '../shared-authority';
import { StudioStore } from '../store';
import { hire, ID, makeStudio, seedOrg } from './helpers';
const paths: string[] = [];
afterEach(() => { for (const path of paths.splice(0)) rmSync(path, { recursive: true, force: true }); });
it('pairs committed shared authority with acquisition and fences actual Studio block/restore', async () => {
  const h = makeStudio(), users = await seedOrg(h), { agent } = await hire(h, users.alice);
  const path = mkdtempSync(join(tmpdir(), 'vox-shared-studio-authority-')); paths.push(path);
  const initial = await h.studio.deps.store.read();
  const store = new StudioStore(path); await store.update(s => Object.assign(s, initial));
  const authority = sharedAuthorityFromStudioStore(store);
  const before = await authority.member(ID.alice);
  expect(authority.memberNow!(ID.alice)).toEqual(before);
  expect(authority.agentNow!(agent.id)).toEqual(await authority.agent(agent.id));
  await h.studio.blockByAgent(agent.id, ID.alice);
  const blocked = await h.studio.deps.store.read(); await store.update(s => Object.assign(s, blocked));
  expect(authority.memberNow!(ID.alice).agentIds).not.toContain(agent.id);
  await h.studio.unblock(users.alice, agent.id, ID.alice);
  const restored = await h.studio.deps.store.read(); await store.update(s => Object.assign(s, restored));
  expect(authority.memberNow!(ID.alice).agentIds).toContain(agent.id);
  expect(authority.memberNow!(ID.alice).revision).not.toBe(before.revision);
  expect(authority.memberNow!(ID.alice)).toEqual(await authority.member(ID.alice));
  await store.update(s => { s.members.find(m => m.telegramId === ID.alice)!.firstName = 'Display changed'; });
  const display = authority.memberNow!(ID.alice);
  expect(display.revision).toBe((await authority.member(ID.alice)).revision);
  await store.update(s => { s.agents.find(a => a.id === agent.id)!.learningAuthorityRevision = -1; });
  expect(() => authority.agentNow!(agent.id)).toThrow('Invalid Studio authority');
});
