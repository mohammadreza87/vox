import { afterEach, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { transpileModule, ModuleKind } from 'typescript';
import * as crypto from 'node:crypto';
import * as zod from 'zod';
import * as runtime from '../runtime/contracts';
import * as relationships from '../relationships/contracts';
import * as observation from '../observation/contracts';
import type { AdaptiveRepository } from '../persistence/repository';
import { correctionFixture, CORRECTION_NOW } from './memory-correction-fixtures';
const fixtures: Awaited<ReturnType<typeof correctionFixture>>[]=[];
afterEach(async()=>{await Promise.all(fixtures.splice(0).map(f=>f.close()));});
it('exact baseline943e4e6 strict repository reads corrections/events/derived tombstones without stripping or restoring any data',async()=>{
  const source=readFileSync('src/lib/adaptive/__tests__/compatibility/base943e4e6/repository.ts.fixture','utf8');
  expect(createHash('sha256').update(source).digest('hex')).toBe('27376116c41abdceaf7f2d07deaa3e54d4ce7e957f5242c0ce370e62a34905dc');
  const modules:Record<string,unknown>={crypto,zod,'../runtime/contracts':runtime,'../relationships/contracts':relationships,'../observation/contracts':observation};
  const exports:Record<string,unknown>={};
  new Function('require','exports',transpileModule(source,{compilerOptions:{module:ModuleKind.CommonJS}}).outputText)((id:string)=>{if(!(id in modules))throw Error(`Unexpected historical import ${id}`);return modules[id];},exports);
  const OldRepository=exports.AdaptiveRepository as typeof AdaptiveRepository;
  const f=await correctionFixture();fixtures.push(f);
  await f.service.withAccountDocument(123,d=>{d.memories[0].origin='user_reviewed_claim';d.memories.push({...d.memories[0],id:'derived',text:'OLD_SUMMARY',sourceRefs:[{id:f.note.id,revision:1}]});});
  const event=f.input('Latest explicit correction');await f.service.correctMemory(123,f.note.id,event,{authorizeNow:()=>true});
  const before=f.storage.readCommittedForEffect!('telegram-account:123');expect(before.status).toBe('ready');
  const old=new OldRepository(f.storage);const prior=old.readCommittedForEffect('telegram-account:123',CORRECTION_NOW);expect(prior.status).toBe('ready');
  if(prior.status!=='ready'||!prior.document)throw Error('Missing historical document');
  expect(prior.document.memories[0]).toMatchObject({text:event.text,revision:2,revocationEpoch:1,origin:'user_reviewed_claim'});
  expect(prior.document.memories[1]).toMatchObject({status:'deleted',revision:2,revocationEpoch:1});expect(prior.document.memories[1].text).toBeUndefined();
  expect(prior.document.events.some(e=>e.eventId===event.eventId&&e.kind==='memory_corrected')).toBe(true);
  expect(prior.document.outbox.some(e=>e.memoryId==='derived'&&e.kind==='memory_deleted')).toBe(true);
  await old.transaction('telegram-account:123',CORRECTION_NOW,()=>undefined);
  expect(f.storage.readCommittedForEffect!('telegram-account:123')).toEqual(before);
});
