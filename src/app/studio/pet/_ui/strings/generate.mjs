#!/usr/bin/env node
/**
 * The pet's string catalogue, generated from the copy keys file (docs/design/PET_COPY_KEYS_2026_10_26.md).
 * The keys file is the source of truth: EN column for English, FA column (the Persian copywriter's text) for
 * Persian, copied verbatim. Variants written in a cell as «a» / «b» become arrays. Never hand-edit keys.ts,
 * en.ts, fa.ts or voice.ts: change the keys file and run
 *
 *   node src/app/studio/pet/_ui/strings/generate.mjs
 *
 * strings.test.ts parses the keys file again and fails when the catalogue has drifted from it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const FILE = import.meta.url.startsWith('file:') ? fileURLToPath(import.meta.url) : null;
/** This folder (under a test runner whose module URLs are not file: URLs, from the repository root). */
export const HERE = FILE ? join(FILE, '..') : join(process.cwd(), 'src/app/studio/pet/_ui/strings');
export const KEYS_DOC = join(HERE, '../../../../../../docs/design/PET_COPY_KEYS_2026_10_26.md');

/**
 * Keys the file marks as legal-process text ("as drafted in PRIVACY_AND_CONSENT.md"): no copy in the keys file at
 * all, so they are not in the catalogue. Their sheets take the privacy doc's own approved text.
 */
export const LEGAL_KEYS = ['perm.P3.*', 'perm.P5.*'];

const cells = (line) => line.split('|').slice(1, -1).map((c) => c.trim());
const unquote = (s) => s.replace(/^«/, '').replace(/»$/, '');

/** An FA cell: «one», or «a» / «b» variants, or the haft-sin list «a»، «b». Inner «quotes» are kept. */
function faValue(cell) {
  if (!cell.startsWith('«') || !cell.endsWith('»')) return null;
  if (cell.includes('» / «')) return cell.split(' / ').map(unquote);
  if (cell.includes('»، «')) return cell.split('، ').map(unquote);
  return unquote(cell);
}

/** English cells: the page's typographic apostrophe (’, as copy.ts always used); the gloss note in brackets dropped. */
function enValue(cell, key, fa) {
  if (key === 'season.haftsin.*') return cell.replace(/\s*\(labels\)$/, '').split(', ');
  // the gloss of a line said in Persian: the note in brackets is for the reader of the keys file
  const text = cell.replace(/\s*\((?:the traditional line;[^)]*)\)$/, '').replace(/'/g, '’');
  return Array.isArray(fa) && text.includes(' / ') ? text.split(' / ') : text;
}

/** Every key row: { key, surface, voice, en, fa } with fa null when the FA cell holds no copy. */
export function parseKeysDoc(md) {
  const out = [];
  let cols = null;
  for (const line of md.split('\n')) {
    if (!line.startsWith('|')) { cols = null; continue; }
    const c = cells(line);
    if (c[0] === 'Key') { cols = c; continue; }
    if (!cols || !c[0].startsWith('`')) continue;
    const at = (name) => c[cols.indexOf(name)];
    const key = c[0].replace(/`/g, '');
    const surface = at('Surface');
    const voice = cols.includes('Voice') ? at('Voice') : 'system';
    const faCell = at('FA');
    if (LEGAL_KEYS.includes(key)) continue;
    const fa = faValue(faCell);
    out.push({ key, surface, voice, en: enValue(at('English'), key, fa), fa });
  }
  return out;
}

/**
 * The English the living page paints before a catalogue chunk arrives (and all a Home-room session needs in
 * English): the engine's say lines, the Home dock and its needs, the room names, talk pill, quiet screens and page
 * buttons. The full catalogues load lazily (index.ts), so the route carries ~1 KB of copy, not ~11 KB. Each away room's
 * verbs (`toy.play.*` …) are left out: a room chunk paints only once the catalogue has loaded (rooms/index.ts); so is
 * the coach chip's `ui.dismiss` (Extras mounts after hello) and the unused `ui.less`.
 */
export const CORE = /^(say\.(hi|hiName|achoo|hmph|okayOkay|yum|soFull|napFirst|fiveMore|learned|aww)|chip\.(firstDay|daysTogether)|talk\.(placeholder|chatInTelegram|holdToTalk|recording|micBlocked|failed|didntCatch|reopen)|toy\.[A-Za-z]+|ui\.(retry|close|more|send|toys|rooms))$|^(room|quiet|need)\./;

const lit = (v) => (Array.isArray(v) ? `[${v.map((s) => JSON.stringify(s)).join(', ')}]` : JSON.stringify(v));
const HEAD = '/* Generated by strings/generate.mjs from docs/design/PET_COPY_KEYS_2026_10_26.md. Do not edit by hand. */\n';

export function render(rows) {
  const keys = `${HEAD}\nexport type PetStringKey =\n${rows.map((r) => `  | '${r.key}'`).join('\n')};\n`;
  const en = `${HEAD}\nimport type { PetStringKey } from './keys';\nimport type { PetString } from './types';\n\nexport const EN: Record<PetStringKey, PetString> = {\n${rows.map((r) => `  '${r.key}': ${lit(r.en)},`).join('\n')}\n};\n`;
  const fa = `${HEAD}/* The Persian copywriter's text, verbatim. A key missing here falls back to English (see FA_MISSING in strings.test.ts). */\n\nimport type { PetStringKey } from './keys';\nimport type { PetString } from './types';\n\nexport { voiceOf } from './voice';\n\nexport const FA: Partial<Record<PetStringKey, PetString>> = {\n${rows.filter((r) => r.fa !== null).map((r) => `  '${r.key}': ${lit(r.fa)},`).join('\n')}\n};\n`;
  const voice = `${HEAD}\nimport type { PetStringKey } from './keys';\n\n/** Who speaks each line (voice guide §3): pet (تو, spoken), system (شما, Persian digits), person (the human's own words). */\nexport type PetVoice = 'pet' | 'system' | 'person';\n\n/** Every key that is not system voice; the rest are system. */\nexport const NOT_SYSTEM: Partial<Record<PetStringKey, Exclude<PetVoice, 'system'>>> = {\n${rows.filter((r) => r.voice !== 'system').map((r) => `  '${r.key}': '${r.voice}',`).join('\n')}\n};\n\nexport const voiceOf = (key: PetStringKey): PetVoice => NOT_SYSTEM[key] ?? 'system';\n`;
  const core = `${HEAD}/* English for the first paint (CORE in generate.mjs); en.ts holds every key. */\n\nimport type { PetStringKey } from './keys';\n\nexport const CORE: Partial<Record<PetStringKey, string>> = {\n${rows.filter((r) => CORE.test(r.key) && typeof r.en === 'string').map((r) => `  '${r.key}': ${lit(r.en)},`).join('\n')}\n};\n`;
  return { 'keys.ts': keys, 'en.ts': en, 'fa.ts': fa, 'voice.ts': voice, 'core.ts': core };
}

/**
 * The server's copy of the check-in DM templates (care game design §5.3-§5.4), for src/lib/pet/checkin-copy.ts: the
 * server cannot import this client folder. Every check-in key (`ci.*`, and `dm.*` / `checkin.*` if the keys file ever
 * adds them) plus the P1 consent sheet (`perm.P1.*`, whose exact text the consent evidence hashes). Every value is an
 * array of variants (one today); the FA object leaves out a key with no Persian yet (the server falls back to English).
 * The copy lint reads this file with its own voice map (CHECKIN_VOICE).
 */
export const SERVER_CHECKIN_KEYS = /^(ci|dm|checkin)\.|^perm\.P1\./;
export const SERVER_CHECKIN_FILE = join(HERE, '../../../../../lib/pet/checkin-copy.ts');

export function renderCheckinCopy(rows) {
  const picked = rows.filter((r) => SERVER_CHECKIN_KEYS.test(r.key));
  const arr = (v) => `[${(Array.isArray(v) ? v : [v]).map((s) => JSON.stringify(s)).join(', ')}]`;
  return `${HEAD}/* The check-in DM templates and the P1 consent sheet for the server (strings/generate.mjs renderCheckinCopy). Variants are arrays. */

export type CheckinCopyKey =
${picked.map((r) => `  | '${r.key}'`).join('\n')};
export type CheckinLang = 'en' | 'fa';
export type CheckinVoice = 'pet' | 'system' | 'person';
export type CheckinCatalog = Readonly<Record<CheckinCopyKey, readonly string[]>>;

/** Who speaks each line (voice guide §3); the copy lint reads this map. */
export const CHECKIN_VOICE: Readonly<Record<CheckinCopyKey, CheckinVoice>> = {
${picked.map((r) => `  '${r.key}': '${r.voice}',`).join('\n')}
};

export const EN: CheckinCatalog = {
${picked.map((r) => `  '${r.key}': ${arr(r.en)},`).join('\n')}
};

/** The Persian copywriter's text, verbatim. A key missing here falls back to English. */
export const FA: Readonly<Partial<Record<CheckinCopyKey, readonly string[]>>> = {
${picked.filter((r) => r.fa !== null).map((r) => `  '${r.key}': ${arr(r.fa)},`).join('\n')}
};

for (const catalog of [CHECKIN_VOICE, EN, FA]) {
  for (const value of Object.values(catalog)) if (Array.isArray(value)) Object.freeze(value);
  Object.freeze(catalog);
}
`;
}

if (FILE && process.argv[1] === FILE) {
  const rows = parseKeysDoc(readFileSync(KEYS_DOC, 'utf8'));
  const files = render(rows);
  for (const [name, text] of Object.entries(files)) writeFileSync(join(HERE, name), text);
  writeFileSync(SERVER_CHECKIN_FILE, renderCheckinCopy(rows));
  console.log(`wrote ${Object.keys(files).join(', ')}, src/lib/pet/checkin-copy.ts`);
}
